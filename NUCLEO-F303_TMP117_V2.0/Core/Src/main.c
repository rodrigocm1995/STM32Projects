void TMP117_Initialization(void)
{
    const char *msg;
    static char err_buffer[120];

    if (TMP117_Init(&tmp117, &hi2c1, TMP117_ADDRESS) == HAL_OK) 
    { 
        msg = "Inicialización correcta\r\n"; 
    } 
    else 
    { 
        msg = "Inicialización fallida\r\n"; 
    }
    HAL_UART_Transmit_DMA(&huart2, (uint8_t *)msg, strlen(msg));

    while (huart2.gState != HAL_UART_STATE_READY); // Espera obligatoria de DMA
    if (TMP117_SetLowLimit_C(&tmp117, lowLimitTemp) == HAL_OK) 
    { 
        msg = "Correct initialization of the lower temperature limit\r\n"; 
    } 
    else 
    { 
        msg = "Lower temperature limit initialization failed\r\n"; 
    }
    HAL_UART_Transmit_DMA(&huart2, (uint8_t *)msg, strlen(msg));

    while (huart2.gState != HAL_UART_STATE_READY);
    if (TMP117_SetHighLimit_C(&tmp117, highLimitTemp) == HAL_OK) 
    { msg = "Correct initialization of the upper temperature limit\r\n"; 
    } 
    else 
    { 
        msg = "Upper temperature limit initialization failed\r\n"; 
    }
    HAL_UART_Transmit_DMA(&huart2, (uint8_t *)msg, strlen(msg));

    while (huart2.gState != HAL_UART_STATE_READY);
    if (TMP117_SetConvTime(&tmp117, TMP117_CONV_4_S) == HAL_OK)
    {
        msg = "Tiempo de conversion configurado a 4s correctamente\r\n";
        HAL_UART_Transmit_DMA(&huart2, (uint8_t *)msg, strlen(msg));
    }
    else
    {
        // Si falla, formateamos los datos dinámicos usando snprintf en el buffer estático
        snprintf(err_buffer, sizeof(err_buffer), "ERROR: requested time (%.1f ms) is less than active time (%.1f ms)\r\n", tmp117._requestedTime, tmp117._activeTime);
      
        HAL_UART_Transmit_DMA(&huart2, (uint8_t *)err_buffer, strlen(err_buffer));
    }
}

void Task_Read_TMP117(void)
{
    static char tx_buffer[60];

    if (readTicks >= 20)
    {
        readTicks = 0;

        if (TMP117_IsDataReady(&tmp117))
        {
            temperatureC = TMP117_GetTemperature_C(&tmp117);

            while (huart2.gState != HAL_UART_STATE_READY);
            snprintf(tx_buffer, sizeof(tx_buffer), "Temperatura: %.4f C\r\n", temperatureC);
            HAL_UART_Transmit_DMA(&huart2, (uint8_t *)tx_buffer, strlen(tx_buffer));
        }
    }
}

void Task_Led_Blink(void)
{
    uint32_t blinkLimit = 10;

    if (temperatureC <= 25.0f) 
    {
        blinkLimit = 10; // 1 Hz (Periodo 1000ms -> Toggle 500ms -> 10 ticks)
    } 
    else if (temperatureC > 25.0f && temperatureC < 35.0f) 
    {
        blinkLimit = 2;  // 5 Hz (Periodo 200ms -> Toggle 100ms -> 2 ticks)
    } 
    else if (temperatureC >= 35.0f) 
    {
        blinkLimit = 1;  // 20 Hz (Periodo 50ms -> Toggle 25ms -> 1 tick aproximado)
    }

    if (blinkTicks >= blinkLimit)
    {
        blinkTicks = 0; 
        HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
    }
}
