void Task_Display(void)
{
    static uint8_t currentDigit = 0;

    uint8_t bytePattern = digitsArray[currentDigit];

    for (uint8_t i = 0; i < SEGMENTS_SIZE; i++)
    {
        GPIO_PinState state = (bytePattern & (1 << i)) ? GPIO_PIN_SET : GPIO_PIN_RESET;
        
        HAL_GPIO_WritePin(segmentsArray[i].Port, segmentsArray[i].Pin, state);
    }

    currentDigit++;
    
    if (currentDigit >= DIGITS_SIZE)
    {
        currentDigit = 0;
    }
}
